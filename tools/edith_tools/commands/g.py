def _pct(vals: list[float], p: float) -> float | None:
    if not vals:
        return None
    s = sorted(vals)
    return s[max(1, min(len(s), math.ceil(p / 100 * len(s)))) - 1]


def _r(v):
    return None if v is None else round(v, 3)


def t13_stats(sent: dict[int, float], echoes: dict[int, tuple[float, float]], fps: int,
              send_span_s: float) -> dict:
    """T13 statistics (TESTS.md §T13 latency definition).

    sent: frame_id -> peer send time (s); echoes: frame_id -> (peer echo-receive time (s),
    glasses recv→decoded ms). RTT = echo_rx - send (peer clock only). One-way latency estimate
    = (RTT - decode)/2 + decode, i.e. half the network round trip plus the decode time.
    """
    rtt, dec, lat = [], [], []
    for fid, (t_rx, d_ms) in echoes.items():
        if fid not in sent:
            continue
        r_ms = (t_rx - sent[fid]) * 1000
        rtt.append(r_ms)
        dec.append(d_ms)
        lat.append(max(0.0, r_ms - d_ms) / 2 + d_ms)
    n_sent = len(sent)
    n_echo = len([f for f in echoes if f in sent])
    dropped = n_sent - n_echo
    drop_pct = 100.0 * dropped / n_sent if n_sent else None
    res = {
        "sent": n_sent, "echoed": n_echo, "dropped": dropped, "drop_pct": _r(drop_pct),
        "fps_requested": fps, "achieved_fps": _r(n_sent / send_span_s) if send_span_s > 0 else None,
        "rtt_ms_p50": _r(_pct(rtt, 50)), "rtt_ms_p95": _r(_pct(rtt, 95)), "rtt_ms_max": _r(max(rtt) if rtt else None),
        "decode_ms_p50": _r(_pct(dec, 50)), "decode_ms_p95": _r(_pct(dec, 95)),
        "latency_ms_p50": _r(_pct(lat, 50)), "latency_ms_p95": _r(_pct(lat, 95)),
        "latency_definition": "(rtt - decode)/2 + decode, rtt on the peer clock only",
        "thresholds": {"latency_ms_p95_max": 150, "drop_pct_max": 2, "decode_ms_p95_max": 10},
    }
    res["pass"] = bool(
        n_sent and res["latency_ms_p95"] is not None and res["latency_ms_p95"] <= 150
        and drop_pct is not None and drop_pct < 2 and res["decode_ms_p95"] is not None
        and res["decode_ms_p95"] < 10)
    return res


class Peer:
    """State for one `selftest --serve` run; files go to `run_dir` (runs/bringup/<ts>/)."""

    def __init__(self, run_dir: Path, token: str | None, quiet: bool = False) -> None:
        self.run_dir = run_dir
        self.token = token
        self.quiet = quiet
        self.frames: list[bytes] | None = None
        run_dir.mkdir(parents=True, exist_ok=True)
        self.log_path = run_dir / "peer.log"

    def log(self, msg: str) -> None:
        line = f"{datetime.now(UTC).strftime('%H:%M:%S.%f')[:-3]} {msg}"
        with self.log_path.open("a") as f:
            f.write(line + "\n")
        if not self.quiet:
            print(line, flush=True)

    def append_json(self, name: str, rec: dict) -> None:
        with (self.run_dir / name).open("a") as f:
            f.write(json.dumps(rec) + "\n")

    def authorized(self, request) -> bool:
        if not self.token:
            return True
        q = request.query.get("token")
        h = request.headers.get("Authorization", "")
        return secrets.compare_digest(q or "", self.token) or secrets.compare_digest(h, f"Bearer {self.token}")


def make_app(peer: Peer):
    from aiohttp import WSMsgType, web

    async def healthz(request):
        return web.json_response({"ok": True, "run_dir": str(peer.run_dir)})

    def deny(request):
        peer.log(f"401 from {request.remote} {request.path}")
        return web.json_response({"error": "bad token"}, status=401)

    async def t11_down(request):
        if not peer.authorized(request):
            return deny(request)
        n = min(int(request.query.get("bytes", 8 << 20)), 512 << 20)
        resp = web.StreamResponse(headers={"Content-Type": "application/octet-stream", "Content-Length": str(n)})
        await resp.prepare(request)
        chunk = b"\x5a" * (1 << 16)
        t0 = time.perf_counter()
        left = n
        while left > 0:
            k = min(left, len(chunk))
            await resp.write(chunk[:k])
            left -= k
        await resp.write_eof()
        s = time.perf_counter() - t0
        peer.append_json("t11.jsonl", {"dir": "down", "bytes": n, "secs": round(s, 4),
                                       "mbit_s_peer": round(n * 8 / 1e6 / s, 2) if s else None,
                                       "remote": request.remote})
        peer.log(f"T11 down {n} B in {s:.2f} s")
        return resp

    async def t11_up(request):
        if not peer.authorized(request):
            return deny(request)
        t0 = time.perf_counter()
        n = 0
        async for chunk in request.content.iter_chunked(1 << 16):
            n += len(chunk)
        s = time.perf_counter() - t0
        rec = {"dir": "up", "bytes": n, "secs": round(s, 4),
               "mbit_s_peer": round(n * 8 / 1e6 / s, 2) if s else None, "remote": request.remote}
        peer.append_json("t11.jsonl", rec)
        peer.log(f"T11 up {n} B in {s:.2f} s")
        return web.json_response(rec)

    async def ws_handler(request):
        if not peer.authorized(request):
            return deny(request)
        test = request.query.get("test", "")
        ws = web.WebSocketResponse(max_msg_size=8 << 20, heartbeat=None)
        await ws.prepare(request)
        peer.log(f"WS open test={test or '?'} from {request.remote}")
        await ws.send_json({"type": "hello", "test": test, "peer_version": 1, "run_dir": str(peer.run_dir)})
        t9 = {"wav": None, "segment": None, "samples": 0, "sumsq": 0.0}
        t13 = {"sent": {}, "echoes": {}, "task": None}

        def t9_close() -> dict | None:
            if t9["wav"] is None:
                return None
            t9["wav"].close()
            n = t9["samples"]
            rms = math.sqrt(t9["sumsq"] / n) / 32768 if n else 0.0
            rec = {"type": "t9.saved", "segment": t9["segment"], "path": t9["path"], "samples": n,
                   "rms_dbfs": round(20 * math.log10(rms), 2) if rms > 1e-6 else -120.0}
            t9["wav"] = None
            peer.append_json("t9.jsonl", {**rec, "rate": t9["rate"], "channels": t9["channels"],
                                          "source": t9["source"]})
            peer.log(f"T9 saved {rec['path']} ({n} samples, {rec['rms_dbfs']} dBFS)")
            return rec

        async def t13_send(fps: int, seconds: float) -> None:
            if peer.frames is None:
                peer.frames = await asyncio.get_running_loop().run_in_executor(None, make_t13_frames)
            frames = peer.frames
            total = int(round(fps * seconds))
            t0 = time.perf_counter()
            for i in range(total):
                target = t0 + i / fps
                delay = target - time.perf_counter()
                if delay > 0:
                    await asyncio.sleep(delay)
                if ws.closed:
                    break
                t13["sent"][i] = time.perf_counter()
                await ws.send_bytes(b"\x0d" + struct.pack(">I", i) + frames[i % len(frames)])
            span = time.perf_counter() - t0
            deadline = time.perf_counter() + 2.0  # grace for the last echoes
            while time.perf_counter() < deadline and len(t13["echoes"]) < len(t13["sent"]):
                await asyncio.sleep(0.05)
            res = t13_stats(t13["sent"], t13["echoes"], fps, span)
            res["frame_bytes_mean"] = int(sum(map(len, frames)) / len(frames))
            peer.append_json("t13.jsonl", {**res, "remote": request.remote,
                                           "rtt_ms": {k: round((v[0] - t13["sent"][k]) * 1000, 3)
                                                      for k, v in t13["echoes"].items() if k in t13["sent"]},
                                           "decode_ms": {k: v[1] for k, v in t13["echoes"].items()}})
            peer.log(f"T13 result sent={res['sent']} drop%={res['drop_pct']} "
                     f"lat_p95={res['latency_ms_p95']} rtt_p95={res['rtt_ms_p95']} "
                     f"dec_p95={res['decode_ms_p95']} pass={res['pass']}")
            if not ws.closed:
                await ws.send_json({"type": "t13.result", **res})

        try:
            async for msg in ws:
                if msg.type == WSMsgType.BINARY:
                    if t9["wav"] is not None:
                        data = msg.data
                        t9["wav"].writeframesraw(data)
                        cnt = len(data) // 2
                        t9["samples"] += cnt
                        t9["sumsq"] += sum(v * v for v in struct.unpack(f"<{cnt}h", data[:cnt * 2]))
                    continue
                if msg.type != WSMsgType.TEXT:
                    continue
                try:
                    m = json.loads(msg.data)
                except ValueError:
                    await ws.send_json({"type": "error", "error": "bad json"})
                    continue
                typ = m.get("type")
                if typ == "t9.start":
                    t9_close()
                    seg = re.sub(r"[^A-Za-z0-9_.-]", "_", str(m.get("segment", "seg")))[:64]
                    path = peer.run_dir / f"t9_{seg}.wav"
                    w = wave.open(str(path), "wb")
                    w.setnchannels(int(m.get("channels", 1)))
                    w.setsampwidth(2)
                    w.setframerate(int(m.get("rate", 16000)))
                    t9.update(wav=w, segment=seg, samples=0, sumsq=0.0, path=str(path.relative_to(ROOT))
                              if path.is_relative_to(ROOT) else str(path), rate=m.get("rate"),
                              channels=m.get("channels"), source=m.get("source"))
                    peer.log(f"T9 start {seg} source={m.get('source')} rate={m.get('rate')} ch={m.get('channels')}")
                elif typ == "t9.end":
                    rec = t9_close()
                    await ws.send_json(rec or {"type": "t9.saved", "segment": m.get("segment"), "path": None, "samples": 0})
                elif typ == "t13.start":
                    fps = max(1, min(60, int(m.get("fps", 15))))
                    seconds = max(0.5, min(600.0, float(m.get("seconds", 60))))
                    peer.log(f"T13 start fps={fps} seconds={seconds}")
                    t13["task"] = asyncio.create_task(t13_send(fps, seconds))
                elif typ == "t13.echo":
                    fid = int(m.get("frame_id", -1))
                    if fid in t13["sent"] and fid not in t13["echoes"]:
                        t13["echoes"][fid] = (time.perf_counter(), float(m.get("recv_to_decoded_ms", 0.0)))
                elif typ == "t11.ping":
                    await ws.send_json({"type": "t11.pong", "seq": m.get("seq")})
                elif typ == "bye":
                    break
                else:
                    await ws.send_json({"type": "error", "error": f"unknown type {typ}"})
        finally:
            t9_close()
            task = t13["task"]
            if task is not None and not task.done():
                task.cancel()
            peer.log(f"WS close test={test or '?'}")
        return ws

    app = web.Application(client_max_size=600 << 20)
    app.router.add_get("/healthz", healthz)
    app.router.add_get("/v1/selftest", ws_handler)
    app.router.add_get("/v1/selftest/t11/down", t11_down)
    app.router.add_post("/v1/selftest/t11/up", t11_up)
    return app


def lan_ips() -> list[str]:
    ips = []
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("10.255.255.255", 1))  # no packet is sent
            ips.append(s.getsockname()[0])
    except OSError:
        pass
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ip = info[4][0]
            if ip not in ips and not ip.startswith("127."):
                ips.append(ip)
    except OSError:
        pass
    return ips or ["127.0.0.1"]


async def serve(host: str, port: int, out: Path, token: str | None, ready_file: Path | None,
                quiet: bool, duration: float | None) -> None:
    from aiohttp import web

    run_dir = out / _ts()
    peer = Peer(run_dir, token, quiet=quiet)
    runner = web.AppRunner(make_app(peer), access_log=None)
    await runner.setup()
    site = web.TCPSite(runner, host, port)
    await site.start()
    real_port = site._server.sockets[0].getsockname()[1]  # type: ignore[union-attr]
    ips = lan_ips()
    info = {"port": real_port, "host": host, "token": token, "run_dir": str(run_dir), "ips": ips,
            "peer_urls": [f"ws://{ip}:{real_port}/v1/selftest" for ip in ips], "pid": os.getpid()}
    (run_dir / "peer.json").write_text(json.dumps(info, indent=2))
    latest = out / "peer.json"
    latest.write_text(json.dumps(info, indent=2))
    if ready_file:
        ready_file.write_text(json.dumps(info))
    tok = f" --es token {token}" if token else ""
    peer.log(f"selftest peer listening on {host}:{real_port}; results in {run_dir}")
    if not quiet:
        print(f"\nProvision the glasses (or run tools/bringup.sh, which reads {latest}):\n"
              f"  adb shell am start -n {SELFTEST_PKG}/.SelfTestActivity "
              f"--es peer ws://{ips[0]}:{real_port}/v1/selftest{tok}\n"
              "Do not run the companion at the same time. Ctrl-C to stop.\n", flush=True)
    try:
        if duration:
            await asyncio.sleep(duration)
        else:
            await asyncio.Event().wait()
    finally:
        await runner.cleanup()


