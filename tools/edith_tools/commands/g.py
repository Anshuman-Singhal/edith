def aapt2() -> Path:
    home = _android_home()
    if home:
        tools = sorted((home / "build-tools").glob("*/aapt2"),
                       key=lambda p: [int(x) if x.isdigit() else 0 for x in p.parent.name.split(".")])
        if tools:
            return tools[-1]
    found = shutil.which("aapt2")
    if found:
        return Path(found)
    raise FileNotFoundError("aapt2 not found (Android SDK build-tools)")


ALLOWED_PERMS = {"android.permission.CAMERA", "android.permission.RECORD_AUDIO",
                 "android.permission.INTERNET", "android.permission.ACCESS_NETWORK_STATE"}


def check_apk(apk: Path, expect_mercury: bool = True) -> list[tuple[str, bool, str]]:
    """aapt2 checks (C106): badging minSdk/landscape; xmltree meta-data, networkSecurityConfig,
    exact permission set (allowing <pkg>.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION), theme parent."""
    a = str(aapt2())
    badging = subprocess.run([a, "dump", "badging", str(apk)], capture_output=True, text=True, check=True).stdout
    xml = subprocess.run([a, "dump", "xmltree", "--file", "AndroidManifest.xml", str(apk)],
                         capture_output=True, text=True, check=True).stdout
    pkg = re.search(r"package: name='([^']+)'", badging)
    pkg_name = pkg.group(1) if pkg else "?"
    min_sdk = re.search(r"^(?:minSdkVersion|sdkVersion):'(\d+)'", badging, re.M)
    target = re.search(r"^targetSdkVersion:'(\d+)'", badging, re.M)
    perms = set(re.findall(r"uses-permission: name='([^']+)'", badging))
    extra = perms - ALLOWED_PERMS - {f"{pkg_name}.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"}
    # meta-data blocks: name line followed by value line
    meta_true = bool(re.search(
        r'E: meta-data[^\n]*\n(?:\s+A: [^\n]*\n)*?\s+A: [^\n]*:name\([^)]*\)="com\.rayneo\.mercury\.app"[^\n]*\n'
        r'(?:\s+A: [^\n]*\n)*?\s+A: [^\n]*:value\([^)]*\)=(?:true|"true"|\(type 0x12\)0xffffffff)', xml))
    nsc = bool(re.search(r":networkSecurityConfig\([^)]*\)=@", xml))
    orient = re.findall(r":screenOrientation\([^)]*\)=(?:\(type 0x10\))?(\S+)", xml)
    landscape = "android.hardware.screen.landscape" in badging and bool(orient) and all(
        o in ("0", "0x0") for o in orient)
    theme_ok, theme_detail = _theme_parent(a, apk, xml)
    checks = [
        ("badging minSdk 29", bool(min_sdk and min_sdk.group(1) == "29"), f"minSdk={min_sdk.group(1) if min_sdk else None}"),
        ("badging targetSdk 34", bool(target and target.group(1) == "34"), f"targetSdk={target.group(1) if target else None}"),
        ("badging landscape", landscape, f"screenOrientation={orient}"),
        ("xmltree no WRITE_SETTINGS", "android.permission.WRITE_SETTINGS" not in xml, ""),
        ("xmltree networkSecurityConfig", nsc, ""),
        ("permission set exact", not extra and ALLOWED_PERMS <= perms, f"perms={sorted(perms)} extra={sorted(extra)}"),
        ("theme parent AppCompat (dump resources)", theme_ok, theme_detail),
    ]
    checks.insert(3, ("xmltree mercury meta-data=true", meta_true if expect_mercury else True,
                      "com.rayneo.mercury.app" if expect_mercury else "not required"))
    return checks


def _theme_parent(a: str, apk: Path, xml: str) -> tuple[bool, str]:
    m = re.search(r"E: application[^\n]*\n(?:\s+A: [^\n]*\n)*?\s+A: [^\n]*:theme\([^)]*\)=@(0x[0-9a-f]+)", xml)
    if not m:
        return False, "no application theme"
    res = subprocess.run([a, "dump", "resources", str(apk)], capture_output=True, text=True).stdout
    rid = m.group(1).lower()
    # find "resource 0x7f... style/Name" block and its PARENT
    blk = re.search(rf"resource {rid} (style/\S+)[^\n]*\n(.*?)(?=\n\s*resource 0x|\Z)", res, re.S)
    if not blk:
        return False, f"theme {rid} not found in resources"
    parent = re.search(r"PARENT\((?:@?)([^)]+)\)|parent=(\S+)", blk.group(2))
    name = parent and (parent.group(1) or parent.group(2))
    if name and name.startswith("0x"):
        pb = re.search(rf"resource {name.lower()} (style/\S+)", res)
        name = pb.group(1) if pb else name
    ok = bool(name and "Theme.AppCompat" in name)
    return ok, f"{blk.group(1)} parent={name}"


