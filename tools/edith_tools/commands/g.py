def _huff(spec):
    bits, vals = spec
    codes, code, k = {}, 0, 0
    for length in range(1, 17):
        for _ in range(bits[length - 1]):
            codes[vals[k]] = (code, length)
            code += 1
            k += 1
        code <<= 1
    return codes


def _qtable(base: list[int], quality: int) -> list[int]:
    s = 5000 / quality if quality < 50 else 200 - 2 * quality
    return [min(255, max(1, (b * s + 50) // 100)) for b in base]


class _Bits:
    def __init__(self) -> None:
        self.out = bytearray()
        self.acc = 0
        self.n = 0

    def put(self, code: int, length: int) -> None:
        self.acc = (self.acc << length) | (code & ((1 << length) - 1))
        self.n += length
        while self.n >= 8:
            self.n -= 8
            b = (self.acc >> self.n) & 0xFF
            self.out.append(b)
            if b == 0xFF:
                self.out.append(0)

    def flush(self) -> bytes:
        if self.n:
            self.put((1 << (8 - self.n)) - 1, 8 - self.n)
        return bytes(self.out)


def _bitcat(v: int) -> tuple[int, int]:
    n = abs(v).bit_length()
    return n, (v if v >= 0 else v + (1 << n) - 1)


def encode_jpeg_pure(w: int, h: int, pixel, quality: int = 75) -> bytes:
    """Baseline JPEG, YCbCr 4:2:0. `pixel(x, y) -> (r, g, b)`. w and h must be multiples of 16."""
    assert w % 16 == 0 and h % 16 == 0
    ql, qc = _qtable(_QL, quality), _qtable(_QC, quality)
    hdl, hac, cdl, cac = _huff(_DC_L), _huff(_AC_L), _huff(_DC_C), _huff(_AC_C)
    Y = [[0.0] * w for _ in range(h)]
    Cb = [[0.0] * (w // 2) for _ in range(h // 2)]
    Cr = [[0.0] * (w // 2) for _ in range(h // 2)]
    for y in range(h):
        for x in range(w):
            r, g, b = pixel(x, y)
            Y[y][x] = 0.299 * r + 0.587 * g + 0.114 * b - 128
            if x % 2 == 0 and y % 2 == 0:
                Cb[y // 2][x // 2] = -0.1687 * r - 0.3313 * g + 0.5 * b
                Cr[y // 2][x // 2] = 0.5 * r - 0.4187 * g - 0.0813 * b
    bits = _Bits()
    prev = [0, 0, 0]

    def block(plane, bx, by, q, dct, act, ci):
        blk = [plane[by + j][bx:bx + 8] for j in range(8)]
        first = blk[0][0]
        if all(v == first for row in blk for v in row):  # flat fast path: DC only
            coef = [0] * 64
            coef[0] = round(8 * first / q[0])
        else:
            tmp = [[sum(_COS[u][x] * blk[j][x] for x in range(8)) for u in range(8)] for j in range(8)]
            f = [[sum(_COS[v][j] * tmp[j][u] for j in range(8)) for u in range(8)] for v in range(8)]
            coef = [round(f[k // 8][k % 8] / q[k]) for k in _ZIGZAG]
        diff = coef[0] - prev[ci]
        prev[ci] = coef[0]
        n, v = _bitcat(diff)
        bits.put(*dct[n])
        if n:
            bits.put(v, n)
        run = 0
        for k in range(1, 64):
            c = coef[k]
            if c == 0:
                run += 1
                continue
            while run > 15:
                bits.put(*act[0xF0])
                run -= 16
            n, v = _bitcat(c)
            bits.put(*act[(run << 4) | n])
            bits.put(v, n)
            run = 0
        if run:
            bits.put(*act[0x00])

    for my in range(0, h, 16):
        for mx in range(0, w, 16):
            for dy in (0, 8):
                for dx in (0, 8):
                    block(Y, mx + dx, my + dy, ql, hdl, hac, 0)
            block(Cb, mx // 2, my // 2, qc, cdl, cac, 1)
            block(Cr, mx // 2, my // 2, qc, cdl, cac, 2)
    data = bits.flush()

    def seg(marker: int, payload: bytes) -> bytes:
        return struct.pack(">HH", marker, len(payload) + 2) + payload

    def dht(cls_id: int, spec) -> bytes:
        return bytes([cls_id]) + bytes(spec[0]) + bytes(spec[1])

    out = b"\xff\xd8"
    out += seg(0xFFE0, b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00")
    out += seg(0xFFDB, b"\x00" + bytes(ql[k] for k in _ZIGZAG) + b"\x01" + bytes(qc[k] for k in _ZIGZAG))
    out += seg(0xFFC0, struct.pack(">BHHB", 8, h, w, 3) + b"\x01\x22\x00\x02\x11\x01\x03\x11\x01")
    out += seg(0xFFC4, dht(0x00, _DC_L) + dht(0x10, _AC_L) + dht(0x01, _DC_C) + dht(0x11, _AC_C))
    out += seg(0xFFDA, b"\x03\x01\x00\x02\x11\x03\x11\x00\x3f\x00")
    return out + data + b"\xff\xd9"


def make_t13_frames(n: int = 8, w: int = 320, h: int = 240) -> list[bytes]:
    """`n` distinct test frames: a gradient field with a moving bright bar (frame motion)."""
    try:
        import io

        from PIL import Image, ImageDraw

        frames = []
        for i in range(n):
            img = Image.new("RGB", (w, h))
            px = img.load()
            for y in range(h):
                for x in range(w):
                    px[x, y] = ((x * 255) // w, (y * 255) // h, ((x ^ y) * 7 + i * 13) & 0xFF)
            d = ImageDraw.Draw(img)
            bx = (i * w // n)
            d.rectangle([bx, 0, bx + w // n - 1, h - 1], fill=(255, 255, 255))
            d.rectangle([8, 8, w - 9, h - 9], outline=(255, 48, 48), width=2)
            buf = io.BytesIO()
            img.save(buf, "JPEG", quality=75)
            frames.append(buf.getvalue())
        return frames
    except ImportError:
        frames = []
        for i in range(n):
            bx0, bx1 = i * w // n, (i + 1) * w // n

            def pixel(x, y, bx0=bx0, bx1=bx1):
                if bx0 <= x < bx1:
                    return (255, 255, 255)
                return ((x // 16) * 16 * 255 // w, (y // 16) * 16 * 255 // h, 96)

            frames.append(encode_jpeg_pure(w, h, pixel))
        return frames


