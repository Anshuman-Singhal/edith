def parse_tests_md(text: str) -> list[dict]:
    tests = []
    for line in text.splitlines():
        if not re.match(r"^\|\s*T\d+\s*\|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 6:
            raise ValueError(f"TESTS.md row has {len(cells)} cells, expected 6: {line}")
        tid, tier, owner, name, procedure, passc = cells
        tier = "g0" if tier.lower() == "g0" else "all"
        tests.append({
            "id": tid,
            "name": name,
            "tier": tier,
            "tags": ["g0"] if tier == "g0" else [],
            "owners": [o.strip() for o in owner.split(",") if o.strip()],
            "runner": "host" if tid in HOST_TESTS else "apk",
            "procedure": procedure,
            "pass": passc,
            "implemented": tid in IMPLEMENTED,
        })
    return tests


def build_registry() -> dict:
    text = TESTS_MD.read_text()
    tests = parse_tests_md(text)
    return {
        "schema": "edith.bringup.registry/v1",
        "generated_from": "docs/bringup/TESTS.md",
        "tests_md_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "generator": "./edith glasses registry",
        "count": len(tests),
        "tests": tests,
    }


