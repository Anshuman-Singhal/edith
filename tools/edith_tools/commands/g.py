def cmd_dist(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="edith glasses dist")
    ap.add_argument("--selftest", action="store_true", help="only the selftest APK (D13a)")
    ap.add_argument("--no-build", action="store_true", help="package already-built APKs")
    ap.add_argument("--out", type=Path, default=ROOT / "dist")
    a = ap.parse_args(argv)
    if not has_rayneo_sdk():
        print("glasses dist: needs the RayNeo SDK: tools/fetch_rayneo_sdk.sh --from <sample zip>", file=sys.stderr)
        return 1
    wants = [(selftest_apk("rayneo"), SELFTEST_APK_NAME, ":selftest:assembleRayneoDebug")]
    if not a.selftest:
        app = GLASSES / "app-android"
        if (app / "build.gradle.kts").is_file():
            for fl in ("rayneo", "generic"):
                wants.append((app / f"build/outputs/apk/{fl}/debug/app-android-{fl}-debug.apk",
                              f"edith-{fl}-debug.apk", f":app-android:assemble{fl.capitalize()}Debug"))
        else:
            print("glasses dist: app-android (D12) not built yet; packaging the selftest APK only")
    if not a.no_build:
        rc = gradle([t for _, _, t in wants])
        if rc:
            return rc
    for src, _, _ in wants:
        if _report_checks(src, expect_mercury="rayneo" in src.name):
            print(f"glasses dist: aapt2 checks failed for {src}", file=sys.stderr)
            return 1
    a.out.mkdir(parents=True, exist_ok=True)
    lines = []
    for src, name, _ in wants:
        dst = a.out / name
        shutil.copyfile(src, dst)
        lines.append(f"{sha256_file(dst)}  {name}")
    sums = a.out / "SHA256SUMS"
    sums.write_text("\n".join(lines) + "\n")
    print(f"glasses dist: wrote {sums}:")
    print(sums.read_text(), end="")
    return 0


