# JSON Schema validation


def validate_file(schema_path: Path, doc_path: Path) -> list[str]:
    import jsonschema  # pinned in D0

    schema = json.loads(schema_path.read_text())
    doc = json.loads(doc_path.read_text())
    v = jsonschema.Draft202012Validator(schema)
    return [f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
            for e in sorted(v.iter_errors(doc), key=lambda e: list(map(str, e.absolute_path)))]


def cmd_validate(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="edith glasses validate")
    ap.add_argument("--schema", required=True, type=Path)
    ap.add_argument("files", nargs="+", type=Path)
    a = ap.parse_args(argv)
    rc = 0
    for f in a.files:
        errs = validate_file(a.schema, f)
        if errs:
            rc = 1
            print(f"INVALID {f}:\n  " + "\n  ".join(errs[:20]))
        else:
            print(f"valid {f} against {a.schema.name}")
    return rc


