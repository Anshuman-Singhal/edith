def _report_checks(apk: Path, expect_mercury: bool) -> int:
    if not apk.is_file():
        print(f"check-apk: no such APK {apk}", file=sys.stderr)
        return 1
    bad = 0
    print(f"aapt2 checks for {apk.name} (aapt2 {aapt2().parent.name}):")
    for name, ok, detail in check_apk(apk, expect_mercury):
        bad += not ok
        print(f"  {'ok  ' if ok else 'FAIL'}  {name}" + (f"  [{detail}]" if detail else ""))
    return 1 if bad else 0


