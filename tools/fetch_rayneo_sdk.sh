#!/usr/bin/env bash
# Fetch the RayNeo Mercury SDK into a local Maven repo (WS-G; PLAN §3.8, C44, L13).
#
#   tools/fetch_rayneo_sdk.sh --from ~/Downloads/MercuryAndroidSample_v0.2.6.zip   # primary
#   tools/fetch_rayneo_sdk.sh [--url '<tokenized gitbook url>']                   # download
#   tools/fetch_rayneo_sdk.sh --check                                              # verify only
#
# What it does: verify the sample zip's sha256 against glasses/platform-rayneo/sdk.lock;
# extract ONLY the Mercury AAR (into a fresh empty temp dir; the zip is untrusted data);
# verify the AAR's sha256; write glasses/platform-rayneo/libs/m2/com/ffalcon/mercury-sdk/<v>/
# with the AAR and a generated POM. The vendor keystore (xr2-platform.jks) and the IPC AAR
# are never extracted to the repo, and the temp dir is deleted. libs/ is gitignored: the SDK
# is never committed. Downloads retry once on HTTP 429.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK="$ROOT/glasses/platform-rayneo/sdk.lock"
FROM="" URL="" CHECK_ONLY=0

die() { echo "fetch_rayneo_sdk: $*" >&2; exit 1; }
lock() { grep -E "^$1=" "$LOCK" | head -1 | cut -d= -f2-; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --from) FROM="${2:?--from needs a zip path}"; shift 2 ;;
    --url) URL="${2:?--url needs a URL}"; shift 2 ;;
    --check) CHECK_ONLY=1; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

[[ -f "$LOCK" ]] || die "missing $LOCK"
VERSION="$(lock version)"
ZIP_SHA="$(lock sample_zip_sha256)"
AAR_ENTRY="$(lock mercury_aar_entry)"
AAR_SHA="$(lock mercury_aar_sha256)"
DEST="$ROOT/glasses/platform-rayneo/libs/m2/com/ffalcon/mercury-sdk/$VERSION"
AAR_OUT="$DEST/mercury-sdk-$VERSION.aar"
POM_OUT="$DEST/mercury-sdk-$VERSION.pom"

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

if [[ $CHECK_ONLY -eq 1 ]]; then
  [[ -f "$AAR_OUT" && -f "$POM_OUT" ]] || die "SDK repo not present at $DEST"
  [[ "$(sha256 "$AAR_OUT")" == "$AAR_SHA" ]] || die "AAR sha256 mismatch at $AAR_OUT"
  echo "fetch_rayneo_sdk: OK $AAR_OUT"
  exit 0
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/rayneo_sdk.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

if [[ -z "$FROM" ]]; then
  URL="${URL:-$(lock sample_zip_url)}"
  FROM="$TMP/download/sample.zip"; mkdir -p "$TMP/download"
  echo "fetch_rayneo_sdk: downloading sample zip (vendor URLs may be tokenized; prefer --from)"
  for attempt in 1 2; do
    code="$(curl -sS -L -o "$FROM" -w '%{http_code}' "$URL" || echo 000)"
    if [[ "$code" == "200" ]]; then break; fi
    if [[ "$code" == "429" && $attempt -eq 1 ]]; then
      echo "fetch_rayneo_sdk: HTTP 429, retrying once in 10 s"; sleep 10; continue
    fi
    die "download failed (HTTP $code). Download the sample zip in a browser from the RayNeo developer docs and rerun with --from <zip>"
  done
fi

[[ -f "$FROM" ]] || die "no such file: $FROM"
got="$(sha256 "$FROM")"
[[ "$got" == "$ZIP_SHA" ]] || die "sample zip sha256 mismatch: got $got, expected $ZIP_SHA (sdk.lock)"
echo "fetch_rayneo_sdk: sample zip sha256 OK ($got)"

# Extract only the AAR entry into a fresh, empty directory.
mkdir -p "$TMP/x"
if command -v unzip >/dev/null 2>&1; then
  unzip -q -o "$FROM" "$AAR_ENTRY" -d "$TMP/x"
else
  python3 -I -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extract(sys.argv[2], sys.argv[3])' \
    "$FROM" "$AAR_ENTRY" "$TMP/x"
fi
AAR_TMP="$TMP/x/$AAR_ENTRY"
[[ -f "$AAR_TMP" ]] || die "AAR entry $AAR_ENTRY not found in zip"
got="$(sha256 "$AAR_TMP")"
[[ "$got" == "$AAR_SHA" ]] || die "Mercury AAR sha256 mismatch: got $got, expected $AAR_SHA"
echo "fetch_rayneo_sdk: Mercury AAR sha256 OK ($got)"

rm -rf "$DEST"; mkdir -p "$DEST"
cp "$AAR_TMP" "$AAR_OUT"
{
  echo '<?xml version="1.0" encoding="UTF-8"?>'
  echo '<!-- Generated by tools/fetch_rayneo_sdk.sh from glasses/platform-rayneo/sdk.lock. Do not edit. -->'
  echo '<project xmlns="http://maven.apache.org/POM/4.0.0">'
  echo '  <modelVersion>4.0.0</modelVersion>'
  echo "  <groupId>com.ffalcon</groupId><artifactId>mercury-sdk</artifactId><version>$VERSION</version><packaging>aar</packaging>"
  echo '  <dependencies>'
  grep -E '^pom_dep=' "$LOCK" | cut -d= -f2- | while IFS=: read -r g a v; do
    echo "    <dependency><groupId>$g</groupId><artifactId>$a</artifactId><version>$v</version><scope>runtime</scope></dependency>"
  done
  echo '  </dependencies>'
  echo '</project>'
} > "$POM_OUT"

# The keystore and the IPC AAR were never extracted; make sure nothing vendor-signed is left.
find "$ROOT/glasses/platform-rayneo/libs" -name '*.jks' -delete
[[ -z "$(find "$ROOT/glasses/platform-rayneo/libs" -name 'xr2-platform.jks')" ]] || die "keystore present"

groups="$(grep -o '<groupId>[^<]*</groupId>' "$POM_OUT" | sed 1d | sort -u | wc -l | tr -d ' ')"
echo "fetch_rayneo_sdk: wrote $AAR_OUT"
echo "fetch_rayneo_sdk: wrote $POM_OUT ($groups dependency groups)"
echo "fetch_rayneo_sdk: xr2-platform.jks absent; SDK is gitignored (glasses/platform-rayneo/libs/)"
